-- Pathwise Loot's catalog: every dungeon and raid boss, what it drops, the
-- items, search and the wishlist.
--
--   L.Instances() -> { instance, ... }       dungeons by level, then raids
--       instance = { map, name, raid, size, levels = { lo, hi } | nil, encounters = { id, ... } }
--   L.Encounter(id) -> { id, name, map, players, npcs, kills, loot = { entry, ... } } | nil
--       entry = { id, data = true | nil, seen = n | nil }   (data: QuestieDB says so; seen: dropped for you)
--   L.Item(id, quiet) -> { id, name, quality, itemLevel, level, slot, class, subClass, classMask, icon, link, cached }
--   L.Usable(item) -> bool                   your class may use it (as far as the data says)
--   L.Search(text) -> { { item = id, encounter = id }, ... }
--   L.Sources(itemId) -> { encounter id, ... }
--   L.Wish(id, on) / L.Wished(id) / L.Wishlist() -> { { item = id, encounter = id | nil }, ... }
--   L.Upgrade(item) -> isUpgrade, pct        from Pathwise Gear, when it is installed
--   L.Portrait(id) -> file id | nil          the boss's Encounter Journal art
--
-- Facts: Data/Loot.lua (generated by tools/data/loot.lua from Forever's client
-- tables and QuestieDB's Forever data; see its header), the drops seen in game
-- (Learn.lua), and what the game client says about an item (C_Item), which
-- wins where it knows. Every value from the client passes ns.Readable first.

local ADDON, ns = ...
local D = ns.LootData
local L = {}
ns.Loot = L

local readable = ns.Readable

-- Forever's Enum.InventoryType (ItemConstantsDocumentation.lua, Gethe/wow-ui-source,
-- forever branch) -> the slot it fills, as the browser names and groups it.
L.SLOTS = {
	[1] = "Head", [2] = "Neck", [3] = "Shoulder", [4] = "Shirt", [5] = "Chest", [6] = "Waist",
	[7] = "Legs", [8] = "Feet", [9] = "Wrist", [10] = "Hands", [11] = "Finger", [12] = "Trinket",
	[13] = "One-hand", [14] = "Off hand", [15] = "Ranged", [16] = "Back", [17] = "Two-hand",
	[18] = "Bag", [19] = "Tabard", [20] = "Chest", [21] = "Main hand", [22] = "Off hand",
	[23] = "Off hand", [24] = "Ammo", [25] = "Ranged", [26] = "Ranged", [27] = "Quiver", [28] = "Relic",
}
-- The kinds of item the browser sorts loot into (its buttons under the
-- boss's name). "other" is anything not worn: bags, ammo, shirts, tabards,
-- recipes, quest items and the like. A single slot's name ("Two-hand")
-- filters to that slot.
L.SLOT_FILTERS = { { "All", "any" }, { "Armor", "armor" }, { "Weapons", "weapon" }, { "Jewelry", "jewelry" }, { "Other", "other" } }
local KIND = {
	Head = "armor", Shoulder = "armor", Chest = "armor", Wrist = "armor", Hands = "armor", Waist = "armor",
	Legs = "armor", Feet = "armor", Back = "armor",
	["One-hand"] = "weapon", ["Two-hand"] = "weapon", ["Main hand"] = "weapon", ["Off hand"] = "weapon",
	Ranged = "weapon", Relic = "weapon",
	Neck = "jewelry", Finger = "jewelry", Trinket = "jewelry",
}
function L.Kind(item) return KIND[item.slot or ""] or "other" end

function L.SlotMatches(item, filter)
	if not filter or filter == "any" then return true end
	if filter == "armor" or filter == "weapon" or filter == "jewelry" or filter == "other" then return L.Kind(item) == filter end
	return item.slot == filter
end

---------------------------------------------------------------------------
-- Drops seen in game (Learn.lua writes them; account-wide, never reset)
---------------------------------------------------------------------------

-- seen[encounterId] = { name, map, kills, items = { [itemId] = times }, npcs = { [npcId] = true } }
function L.Seen() return ns.Data("seen") end

local function seenOf(id)
	local s = L.Seen()[id]
	return type(s) == "table" and s or nil
end

---------------------------------------------------------------------------
-- Instances and bosses
---------------------------------------------------------------------------

local instances, byMap
local function build()
	instances, byMap = {}, {}
	for _, row in ipairs(D.INSTANCES) do
		local inst = { map = row[1], name = row[2], raid = row[3], size = row[4], levels = row[5], encounters = {} }
		for i, id in ipairs(row[6]) do inst.encounters[i] = id end
		instances[#instances + 1] = inst
		byMap[inst.map] = inst
	end
	-- Bosses the game named that the data does not have (a new patch): under
	-- their instance, or an instance of their own at the end.
	local extra = {}
	for id, s in pairs(L.Seen()) do
		if type(id) == "number" and type(s) == "table" and not D.ENCOUNTERS[id] then extra[#extra + 1] = id end
	end
	table.sort(extra)
	for _, id in ipairs(extra) do
		local s = L.Seen()[id]
		local inst = s.map and byMap[s.map]
		if not inst then
			inst = { map = s.map or 0, name = s.instance or "Other bosses", raid = s.raid or false, size = 0, encounters = {}, learned = true }
			instances[#instances + 1] = inst
			if s.map then byMap[s.map] = inst end
		end
		inst.encounters[#inst.encounters + 1] = id
	end
end

function L.Instances()
	if not instances then build() end
	return instances
end
function L.Instance(map)
	if not byMap then build() end
	return byMap[map]
end
function L.Rebuild() instances, byMap = nil, nil end

function L.Encounter(id)
	local row, s = D.ENCOUNTERS[id], seenOf(id)
	if not row and not s then return nil end
	local e = { id = id, name = row and row[1] or s.name or ("Boss " .. id), map = row and row[2] or s.map,
		players = row and row[3] or 0, npcs = {}, kills = s and s.kills or 0, loot = {} }
	local npcSet = {}
	for _, n in ipairs(row and row[4] or {}) do npcSet[n] = true e.npcs[#e.npcs + 1] = n end
	for n in pairs(s and s.npcs or {}) do if not npcSet[n] then e.npcs[#e.npcs + 1] = n end end
	local index = {}
	for _, item in ipairs(row and row[5] or {}) do
		local entry = { id = item, data = true }
		index[item] = entry
		e.loot[#e.loot + 1] = entry
	end
	local learned = {}
	for item, n in pairs(s and s.items or {}) do
		if type(item) == "number" then
			if index[item] then index[item].seen = n
			else learned[#learned + 1] = { id = item, seen = n } end
		end
	end
	table.sort(learned, function(a, b) return a.id < b.id end)
	for _, entry in ipairs(learned) do e.loot[#e.loot + 1] = entry end
	return e
end

-- The boss's portrait: the file id of its Encounter Journal art, when the
-- game's file list has one by its name (Data/Loot.lua), else nil.
function L.Portrait(id)
	return D.PORTRAITS and D.PORTRAITS[id] or nil
end

-- Is this boss one of several of the same instance with this name (a raid
-- version and a dungeon version)? Then the browser shows its size.
function L.Players(id)
	local e = D.ENCOUNTERS[id]
	return e and e[3] or 0
end

