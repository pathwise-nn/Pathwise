local function clientInfo(id)
	if not (C_Item and C_Item.GetItemInfo) then return nil end
	local ok, name, link, quality, ilvl, req, _, _, _, equipLoc, icon = pcall(C_Item.GetItemInfo, id)
	if not ok then return nil end
	name, link, quality = readable(name), readable(link), readable(quality)
	if not name then return nil end
	return { name = name, link = link, quality = readable(quality), itemLevel = readable(ilvl), level = readable(req), icon = readable(icon), equipLoc = readable(equipLoc) }
end

local function instantIcon(id)
	if C_Item and C_Item.GetItemIconByID then
		local ok, icon = pcall(C_Item.GetItemIconByID, id)
		if ok then return readable(icon) end
	end
	return nil
end

-- Asked once per item: the client loads it and sends ITEM_DATA_LOAD_RESULT /
-- GET_ITEM_INFO_RECEIVED (Learn.lua turns those into ITEMS_CHANGED).
local asked = {}
local function ask(id)
	if asked[id] or not (C_Item and C_Item.RequestLoadItemDataByID) then return end
	asked[id] = true
	pcall(C_Item.RequestLoadItemDataByID, id)
end

-- quiet: do not ask the client to load it (a search over every item).
function L.Item(id, quiet)
	local row = D.ITEMS[id]
	local c = clientInfo(id)
	if not c and not quiet then ask(id) end
	local it = {
		id = id,
		name = (c and c.name) or (row and row[1]) or ("Item " .. id),
		quality = (c and c.quality) or (row and row[2] ~= 0 and row[2]) or nil,
		itemLevel = (c and c.itemLevel) or (row and row[3]) or nil,
		level = (c and c.level) or (row and row[4]) or nil,
		slot = row and L.SLOTS[row[5]] or nil,
		class = row and row[6] or nil, subClass = row and row[7] or nil,
		classMask = row and row[8] or nil,
		icon = (c and c.icon) or instantIcon(id),
		link = (c and c.link) or ("item:" .. id),
		cached = c ~= nil,
	}
	return it
end

-- Your class, as AllowableClass counts them (bit classID - 1).
local function classBit()
	local _, _, classId = UnitClass("player")
	classId = readable(classId)
	if type(classId) ~= "number" or classId < 1 then return nil end
	return 2 ^ (classId - 1)
end

function L.Usable(item)
	local mask = item.classMask
	if not mask then return true end
	local b = classBit()
	if not b then return true end
	return math.floor(mask / b) % 2 == 1
end

---------------------------------------------------------------------------
-- Search and sources
---------------------------------------------------------------------------

local sources -- item id -> { encounter ids } from the data
local function sourcesIndex()
	if sources then return sources end
	sources = {}
	for eid, e in pairs(D.ENCOUNTERS) do
		for _, item in ipairs(e[5]) do
			sources[item] = sources[item] or {}
			table.insert(sources[item], eid)
		end
	end
	for _, list in pairs(sources) do table.sort(list) end
	return sources
end

function L.Sources(itemId)
	local out, set = {}, {}
	for _, eid in ipairs(sourcesIndex()[itemId] or {}) do set[eid] = true out[#out + 1] = eid end
	for eid, s in pairs(L.Seen()) do
		if type(s) == "table" and type(s.items) == "table" and s.items[itemId] and not set[eid] then
			set[eid] = true
			out[#out + 1] = eid
		end
	end
	return out
end

-- Every boss's loot whose name holds `text` (any case), at most `limit`.
function L.Search(text, limit)
	text = tostring(text or ""):lower():gsub("^%s+", ""):gsub("%s+$", "")
	local out = {}
	if #text < 2 then return out end
	limit = limit or 200
	local seen = {}
	local function try(item, eid)
		local key = item .. ":" .. eid
		if seen[key] then return end
		seen[key] = true
		local name = L.Item(item, true).name
		if name:lower():find(text, 1, true) then out[#out + 1] = { item = item, encounter = eid } end
	end
	for _, inst in ipairs(L.Instances()) do
		for _, eid in ipairs(inst.encounters) do
			local e = L.Encounter(eid)
			for _, entry in ipairs(e and e.loot or {}) do
				try(entry.id, eid)
				if #out >= limit then return out end
			end
		end
	end
	return out
end

---------------------------------------------------------------------------
-- The wishlist (per character)
---------------------------------------------------------------------------

-- wishlist[itemId] = encounter id it was added from (or true)
local function wishes() return ns.CharData("wishlist") end

function L.Wished(id) return wishes()[id] ~= nil end
function L.Wish(id, on, encounter)
	if on == nil then on = not L.Wished(id) end
	wishes()[id] = on and (encounter or true) or nil
	ns.Fire("WISHLIST_CHANGED", id, on)
	return on
end
function L.Wishlist()
	local out = {}
	for id, from in pairs(wishes()) do
		if type(id) == "number" then
			local eid = type(from) == "number" and from or L.Sources(id)[1]
			out[#out + 1] = { item = id, encounter = eid }
		end
	end
	table.sort(out, function(a, b)
		local na, nb = L.Item(a.item).name, L.Item(b.item).name
		if na ~= nb then return na < nb end
		return a.item < b.item
	end)
	return out
end

