local function zoneList(s)
	if not (s:find(", ", 1, true) or s:find(" & ", 1, true) or ZONES[s]) then return nil end
	local parts = {}
	for chunk in (s:gsub(" & ", ", ") .. ", "):gmatch("(.-), ") do
		local ru = ZONES[chunk]
		if not ru then return nil end
		parts[#parts + 1] = ru
	end
	if #parts == 0 then return nil end
	if #parts == 1 then return parts[1] end
	local last = table.remove(parts)
	return table.concat(parts, ", ") .. " и " .. last
end

