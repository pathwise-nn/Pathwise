-- Builds Pathwise/Locales/<code>.lua from a translation list:
--
--   tools/locales/en.txt          the English text Pathwise shows, one per line
--                                 (line breaks inside a text written \n)
--   tools/locales/<code>.txt      "<line number><TAB><translation>" for each
--
--   lua5.1 tools/locales/build.lua <code> [<code> ...]   (npm run locales)
--   lua5.1 tools/locales/build.lua --check              every list, nothing written
--
-- The translation takes the English line's leading and trailing spaces. A
-- list is refused when a line is missing, or a translation has more values
-- (%s, %d) than its English, or puts them in another order without saying so
-- (Locale.lua's { "text", 2, 1 } form, written "text<TAB>2,1").
-- Russian (ruRU.lua) is a player's own file and is not built from here.

local DIR = "tools/locales/"
local OUT = "Pathwise/Locales/"

-- Who each list is for: the game's language code(s), the language's name,
-- and what goes at the top of the file.
local LANGS = {
	deDE = { codes = { "deDE" }, name = "German" },
	frFR = { codes = { "frFR" }, name = "French" },
	esES = { codes = { "esES", "esMX" }, name = "Spanish (Spain and Latin America)" },
	ptBR = { codes = { "ptBR" }, name = "Brazilian Portuguese" },
	itIT = { codes = { "itIT" }, name = "Italian" },
	koKR = { codes = { "koKR" }, name = "Korean" },
	zhCN = { codes = { "zhCN" }, name = "Simplified Chinese" },
	zhTW = { codes = { "zhTW" }, name = "Traditional Chinese" },
	-- Units and number style: metres where the game's players use them, and a
	-- decimal comma where they write one.
}
local METRES = { deDE = true, frFR = true, esES = true, ptBR = true, itIT = true, koKR = true, zhCN = true, zhTW = true }
local COMMA = { deDE = true, frFR = true, esES = true, ptBR = true, itIT = true }

local function lines(path)
	local f = io.open(path, "rb")
	if not f then return nil end
	local t = {}
	for l in (f:read("*a"):gsub("\r", "") .. "\n"):gmatch("(.-)\n") do t[#t + 1] = l end
	f:close()
	if t[#t] == "" then t[#t] = nil end
	return t
end

local function specs(s)
	local out = {}
	for spec in s:gsub("%%%%", ""):gmatch("%%[%-%+ #0]*%d*%.?%d*([sdif])") do out[#out + 1] = spec end
	return out
end

local en = assert(lines(DIR .. "en.txt"), "no " .. DIR .. "en.txt")

local function build(code, write)
	local lang = assert(LANGS[code], "unknown language " .. code)
	local list = lines(DIR .. code .. ".txt")
	if not list then return nil, "no " .. DIR .. code .. ".txt" end
	local tr, errors = {}, {}
	for _, l in ipairs(list) do
		local n, text, order = l:match("^(%d+)\t([^\t]*)\t?([%d,]*)$")
		n = tonumber(n)
		if not n or not en[n] then errors[#errors + 1] = "bad line: " .. l
		elseif tr[n] then errors[#errors + 1] = "line " .. n .. " twice"
		else tr[n] = { text = text, order = order ~= "" and order or nil } end
	end
	for n, key in ipairs(en) do
		local t = tr[n]
		if not t then
			errors[#errors + 1] = ("line %d missing: %s"):format(n, key)
		else
			local ks, ts = specs(key), specs(t.text)
			if t.order then
				local idx = {}
				for i in t.order:gmatch("%d+") do idx[#idx + 1] = tonumber(i) end
				for j, i in ipairs(idx) do
					if not ks[i] or ks[i] ~= ts[j] then errors[#errors + 1] = ("line %d: values out of order: %s"):format(n, key) break end
				end
				if #idx ~= #ts then errors[#errors + 1] = ("line %d: %d values, order lists %d"):format(n, #ts, #idx) end
			else
				if #ts > #ks then errors[#errors + 1] = ("line %d: more values than the English: %s"):format(n, key) end
				for i = 1, math.min(#ts, #ks) do
					if ts[i] ~= ks[i] then errors[#errors + 1] = ("line %d: values in another order: %s"):format(n, key) break end
				end
			end
		end
	end
	if #errors > 0 then return nil, table.concat(errors, "\n") end

	local function q(s) return '"' .. s:gsub("\\", "\\\\"):gsub('"', '\\"'):gsub("\\\\n", "\\n") .. '"' end
	local out = {
		("-- Pathwise in %s (%s). GENERATED by tools/locales/build.lua from"):format(lang.name, table.concat(lang.codes, ", ")),
		("-- tools/locales/%s.txt: edit that, then npm run locales. Used only when"):format(code),
		"-- the game runs in this language (Core/Locale.lua); everyone else sees",
		"-- English. A machine translation, not yet checked by a native speaker:",
		"-- corrections are welcome (CONTRIBUTING.md, Translations).",
		"",
		"local ADDON, ns = ...",
		"",
		"local T = {",
	}
	for n, key in ipairs(en) do
		local t = tr[n]
		local lead, trail = key:match("^(%s*)"), key:match("(%s*)$")
		local text = t.text:gsub("^%s+", ""):gsub("%s+$", "")
		if key:match("^%s*$") then lead, trail = "", "" end
		text = lead .. text .. (text ~= "" and trail or "")
		if t.order then
			out[#out + 1] = ("\t[%s] = { %s, %s },"):format(q(key), q(text), t.order:gsub(",", ", "))
		else
			out[#out + 1] = ("\t[%s] = %s,"):format(q(key), q(text))
		end
	end
	out[#out + 1] = "}"
	out[#out + 1] = ""
	local codes = {}
	for _, c in ipairs(lang.codes) do codes[#codes + 1] = ("%q"):format(c) end
	local extras = {}
	if METRES[code] then extras[#extras + 1] = 'units = "metres"' end
	if COMMA[code] then extras[#extras + 1] = "comma = true" end
	out[#out + 1] = ("ns.AddLocale({ %s }, T, nil, { %s })"):format(table.concat(codes, ", "), table.concat(extras, ", "))
	out[#out + 1] = ""
	local text = table.concat(out, "\n")
	if write then
		local f = assert(io.open(OUT .. code .. ".lua", "wb"))
		f:write(text)
		f:close()
	end
	return text
end

local check = arg[1] == "--check"
local wanted = {}
if check or not arg[1] then
	for code in pairs(LANGS) do wanted[#wanted + 1] = code end
	table.sort(wanted)
else
	for i = 1, #arg do wanted[#wanted + 1] = arg[i] end
end
local failed = 0
for _, code in ipairs(wanted) do
	local text, err = build(code, not check)
	if text then
		if check then
			local f = io.open(OUT .. code .. ".lua", "rb")
			local have = f and f:read("*a")
			if f then f:close() end
			if have ~= text then failed = failed + 1 print(code .. ": Locales/" .. code .. ".lua is out of date: npm run locales") end
		else
			print("wrote " .. OUT .. code .. ".lua")
		end
	else
		failed = failed + 1
		print(code .. ":\n" .. err)
	end
end
if failed > 0 then os.exit(1) end
if check then print("every language is up to date") end
