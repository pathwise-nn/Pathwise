-- Writes Pathwise_Insights/Data/Routes.lua: the leveling routes' quest steps,
-- taken from Pathwise/Routes/Leveling.lua, so Pathwise Insights can time the
-- same steps (same routes, same step numbers) for players who do not have
-- Pathwise installed. Only what tells a step is done goes in: each step's
-- quest goals (take, do, hand in) with who they are for and whether they are
-- optional. Steps with no quest keep their number, empty.
--
--   lua5.1 tools/insights/routes.lua            write it (npm run insights:routes)
--   lua5.1 tools/insights/routes.lua --check    exit 1 when it is out of date

local OUT = "Pathwise_Insights/Data/Routes.lua"

local routes = {}
local saved = rawget(_G, "Pathwise")
Pathwise = { RegisterRoute = function(r) routes[#routes + 1] = r end }
assert(loadfile("Pathwise/Routes/Leveling.lua"))("Pathwise", {})
Pathwise = saved

local VERB = { accept = "a", complete = "c", turnin = "t" }

local function list(t)
	local out = {}
	for _, v in ipairs(t) do out[#out + 1] = ("%q"):format(tostring(v)) end
	return "{ " .. table.concat(out, ", ") .. " }"
end

-- Who a step or goal is for: { races = {...}, classes = {...} } -> text.
local function only(o)
	if type(o) ~= "table" then return nil end
	local parts = {}
	if o.races then parts[#parts + 1] = "races = " .. list(o.races) end
	if o.classes then parts[#parts + 1] = "classes = " .. list(o.classes) end
	if #parts == 0 then return nil end
	return "{ " .. table.concat(parts, ", ") .. " }"
end

local function goal(g)
	local v = VERB[g[1]]
	if not v or type(g[2]) ~= "number" then return nil end
	local parts = { ("%q"):format(v), tostring(g[2]) }
	if g.optional then parts[#parts + 1] = "opt = true" end
	local o = only(g.only)
	if o then parts[#parts + 1] = "only = " .. o end
	return "{ " .. table.concat(parts, ", ") .. " }"
end

local function step(st)
	local goals = {}
	for _, g in ipairs(st) do
		local t = goal(g)
		if t then goals[#goals + 1] = t end
	end
	local o = only(st.only)
	if o then goals[#goals + 1] = "only = " .. o end
	return "{ " .. table.concat(goals, ", ") .. " }"
end

local lines = {
	"-- GENERATED by tools/insights/routes.lua from Pathwise/Routes/Leveling.lua:",
	"-- do not edit. The leveling routes' quest steps, with Pathwise's step numbers,",
	"-- for timing them without Pathwise installed (Track.lua). Run",
	"-- npm run insights:routes after the routes change.",
	"",
	"local ADDON, ns = ...",
	"ns.Routes = {",
}
for _, r in ipairs(routes) do
	local head = { ("id = %q"):format(r.id), ("title = %q"):format(r.title or r.id) }
	if r.faction then head[#head + 1] = ("faction = %q"):format(r.faction) end
	if r.races then head[#head + 1] = "races = " .. list(r.races) end
	if r.levels then head[#head + 1] = ("levels = { %d, %d }"):format(r.levels[1], r.levels[2]) end
	if r.map then head[#head + 1] = ("map = %d"):format(r.map) end
	if r.next then head[#head + 1] = ("next = %q"):format(r.next) end
	lines[#lines + 1] = "\t{ " .. table.concat(head, ", ") .. ", steps = {"
	for _, st in ipairs(r.steps) do lines[#lines + 1] = "\t\t" .. step(st) .. "," end
	lines[#lines + 1] = "\t} },"
end
lines[#lines + 1] = "}"
local text = table.concat(lines, "\n") .. "\n"

local f = io.open(OUT, "rb")
local have = f and f:read("*a")
if f then f:close() end
if arg[1] == "--check" then
	if have ~= text then
		io.stderr:write(OUT .. " is out of date: run npm run insights:routes\n")
		os.exit(1)
	end
	print(OUT .. " is up to date")
	return
end
if have == text then print(OUT .. " is up to date") return end
f = assert(io.open(OUT, "wb"))
f:write(text)
f:close()
print(("wrote %s: %d routes"):format(OUT, #routes))
