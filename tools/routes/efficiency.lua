-- Route efficiency: where the leveling routes walk more than they need to.
--
--   lua5.1 tools/routes/efficiency.lua        (run from the repository root)
--
-- Zone sizes in yards come from tools/routes/maps.lua, built from the
-- Forever client's UiMapAssignment table: fetch it with
--   node -e "require('./tools/data/wago.js').table('1.60.1.70790','UiMapAssignment')"
-- then run: lua5.1 tools/routes/efficiency.lua --maps 1.60.1.70790
--
-- Reads only Pathwise's own routes and data. For each leveling route it
-- prints the yards walked between stops (straight lines, same continent),
-- and two kinds of waste:
--   * comeback stops: a stop whose every goal is with a person the route
--     already visited, and could have been done then: an accept whose
--     prerequisites were handed in by that visit and whose level is the
--     route's first level or lower, or a hand-in of a quest finished by then.
--     Moving its goals to the earlier visit removes the stop.
--   * out-and-back legs: a long walk out for one stop and straight back.
-- Its findings are leads: each fix goes into tools/port/fixes.lua by hand,
-- with a why.

local BUILD
local NEAR = 40 -- yards: the same place
local FAR = 400 -- yards: an out-and-back leg

-- Zone rectangles in world yards, from UiMapAssignment (whole-zone rows),
-- kept in tools/routes/maps.lua; `--maps` rebuilds that file from the CSV.
local rects = {}
local MAPS = "tools/routes/maps.lua"
if arg and arg[1] == "--maps" then
	BUILD = arg[2] or "1.60.1.70790"
	local path = "data/sources/wago/" .. BUILD .. "/UiMapAssignment.csv"
	local f = assert(io.open(path, "r"), "missing " .. path .. " (see the header for how to fetch it)")
	local head
	for line in f:lines() do
		local cols = {}
		for v in (line .. ","):gmatch("([^,]*),") do cols[#cols + 1] = v end
		if not head then
			head = {}
			for i, h in ipairs(cols) do head[h] = i end
		else
			local function n(k) return tonumber(cols[head[k]]) end
			if n("UiMin_0") == 0 and n("UiMin_1") == 0 and n("UiMax_0") == 1 and n("UiMax_1") == 1 then
				rects[n("UiMapID")] = { cont = n("MapID"), x0 = n("Region_0"), y0 = n("Region_1"), x1 = n("Region_3"), y1 = n("Region_4") }
			end
		end
	end
	f:close()
	local ids = {}
	for id in pairs(rects) do ids[#ids + 1] = id end
	table.sort(ids)
	local out = assert(io.open(MAPS, "wb"))
	local NL = string.char(10)
	out:write("-- GENERATED by tools/routes/efficiency.lua --maps from the Forever client's", NL)
	out:write("-- UiMapAssignment (wago.tools, build ", BUILD, "): each zone's rectangle in", NL)
	out:write("-- world yards, { continent, x0, y0, x1, y1 }. Do not edit by hand.", NL)
	out:write("return {", NL)
	for _, id in ipairs(ids) do
		local r = rects[id]
		out:write(("\t[%d] = { %d, %s, %s, %s, %s },"):format(id, r.cont, r.x0, r.y0, r.x1, r.y1), NL)
	end
	out:write("}", NL)
	out:close()
	print(("wrote %s: %d zones"):format(MAPS, #ids))
	os.exit(0)
end
for id, r in pairs(dofile(MAPS)) do
	rects[id] = { cont = r[1], x0 = r[2], y0 = r[3], x1 = r[4], y1 = r[5] }
end

-- A map position as continent and world yards (nil when the zone is unknown).
local function world(map, x, y)
	local r = rects[map]
	if not r then return nil end
	return r.cont, r.x1 - (y / 100) * (r.x1 - r.x0), r.y1 - (x / 100) * (r.y1 - r.y0)
end
local function yards(a, b)
	if not (a and b) or a.cont ~= b.cont then return nil end
	return math.sqrt((a.wx - b.wx) ^ 2 + (a.wy - b.wy) ^ 2)
end
local function placeOf(goal)
	local at = goal.at or (goal[1] == "goto" and { goal[2], goal[3], goal[4] })
	if not at then return nil end
	local cont, wx, wy = world(at[1], at[2], at[3])
	return cont and { cont = cont, wx = wx, wy = wy } or nil
end

local data = {}
assert(loadfile("Pathwise/Data/Data.lua"))("Pathwise", data)
local D = data.Data
local routes, byId = {}, {}
local savedPathwise = rawget(_G, "Pathwise")
Pathwise = { RegisterRoute = function(r) routes[#routes + 1] = r byId[r.id] = r end }
assert(loadfile("Pathwise/Routes/Leveling.lua"))("Pathwise", {})
Pathwise = savedPathwise

local prev = {}
for _, r in ipairs(routes) do if r.next then prev[r.next] = prev[r.next] or {} table.insert(prev[r.next], r.id) end end
local function handedBefore(id, seen, out)
	for _, p in ipairs(prev[id] or {}) do
		if not seen[p] then
			seen[p] = true
			for _, step in ipairs(byId[p].steps) do
				for _, g in ipairs(step) do if g[1] == "turnin" then out[g[2]] = true end end
			end
			handedBefore(p, seen, out)
		end
	end
	return out
end

local function plain(step) return not step.only and not step.when end

local M = {}

-- One route's findings: { walked, steps, comebacks = { ... }, outAndBack = { ... } }.
function M.route(r)
	local anchors = {}
	for s, step in ipairs(r.steps) do
		for _, g in ipairs(step) do
			local p = placeOf(g)
			if p then anchors[s] = p break end
		end
	end
	-- Yards walked: from stop to stop, the steps that have a place.
	local walked, last = 0, nil
	local order = {}
	for s = 1, #r.steps do
		if anchors[s] then
			local d = last and yards(anchors[last], anchors[s])
			if d then walked = walked + d end
			order[#order + 1] = s
			last = s
		end
	end

	-- When each quest is accepted and finished on the route (step index).
	local accepted, finished = {}, {}
	for s, step in ipairs(r.steps) do
		for _, g in ipairs(step) do
			if type(g[2]) == "number" then
				if g[1] == "accept" and not accepted[g[2]] then accepted[g[2]] = s end
				if g[1] == "complete" then finished[g[2]] = s end
			end
		end
	end
	local function readyBy(q, s)
		local a = accepted[q]
		if not a or a > s then return false end
		local f = finished[q]
		if f then return f <= s end
		local qd = D.quests[q]
		return qd and not (qd[12] and #qd[12] > 0) -- nothing to do: ready once taken
	end

	-- Comeback stops.
	local comebacks = {}
	local done = handedBefore(r.id, {}, {})
	local doneAt = {} -- quest -> step it is handed in on this route
	for s, step in ipairs(r.steps) do
		for _, g in ipairs(step) do if g[1] == "turnin" and not doneAt[g[2]] then doneAt[g[2]] = s end end
	end
	local function handedBy(q, s) return done[q] or (doneAt[q] and doneAt[q] < s) end
	local visits = {} -- who -> { step, ... } (plain steps only)
	for s, step in ipairs(r.steps) do
		local whos = {}
		for _, g in ipairs(step) do if g.who then whos[g.who] = true end end
		for who in pairs(whos) do visits[who] = visits[who] or {} table.insert(visits[who], s) end
	end
	for j, step in ipairs(r.steps) do
		if plain(step) and #step > 0 then
			local who
			local all = true
			for _, g in ipairs(step) do
				if not (g.who and (g[1] == "accept" or g[1] == "turnin") and not g.optional and not g.only) then all = false break end
				if who and g.who ~= who then all = false break end
				who = g.who
			end
			if all and who then
				-- The latest earlier plain visit to the same person (not the step before).
				local best
				-- The same person at the same spot: objects share names.
				local here
				for _, g in ipairs(step) do here = here or placeOf(g) end
				for _, i in ipairs(visits[who]) do
					local there
					for _, g in ipairs(r.steps[i]) do if g.who == who then there = there or placeOf(g) end end
					local d = yards(here, there)
					if i < j - 1 and plain(r.steps[i]) and d and d < NEAR then best = i end
				end
				if best then
					local can = true
					for _, g in ipairs(step) do
						local q, qd = g[2], D.quests[g[2]]
						if g[1] == "accept" then
							local pre, ok = qd and qd[13], true
							if pre and #pre > 0 then
								ok = false
								for _, p in ipairs(pre) do if handedBy(p, best) then ok = true end end
							end
							for _, p in ipairs(qd and qd[14] or {}) do if not handedBy(p, best) then ok = false end end
							if not qd or (qd[3] or 1) > r.levels[1] then ok = false end
							can = can and ok
						else
							can = can and readyBy(q, best)
						end
					end
					if can then
						local before, after
						for k = j - 1, 1, -1 do if anchors[k] then before = k break end end
						for k = j + 1, #r.steps do if anchors[k] then after = k break end end
						local saved = 0
						if before and after and anchors[j] then
							local a, b, c = yards(anchors[before], anchors[j]), yards(anchors[j], anchors[after]), yards(anchors[before], anchors[after])
							if a and b and c then saved = a + b - c end
						end
						comebacks[#comebacks + 1] = { step = j, to = best, who = who, saved = saved, goals = step }
					end
				end
			end
		end
	end

	-- Out-and-back legs: A, B, A' with A' at A and B far away.
	local outAndBack = {}
	for k = 2, #order - 1 do
		local a, b, c = anchors[order[k - 1]], anchors[order[k]], anchors[order[k + 1]]
		local ac, ab = yards(a, c), yards(a, b)
		if ac and ab and ac < NEAR and ab > FAR then
			-- Needed when the way back hands in a quest that opens the next
			-- one taken there (a chain), or hands in what the leg finished.
			local back = r.steps[order[k + 1]]
			local handed = {}
			for _, g in ipairs(back) do if g[1] == "turnin" then handed[g[2]] = true end end
			local chain = false
			for _, g in ipairs(back) do
				local qd = g[1] == "accept" and D.quests[g[2]]
				for _, p in ipairs(qd and qd[13] or {}) do if handed[p] then chain = true end end
				for _, p in ipairs(qd and qd[14] or {}) do if handed[p] then chain = true end end
			end
			outAndBack[#outAndBack + 1] = { step = order[k], yards = 2 * ab, chain = chain }
		end
	end

	return { walked = walked, steps = #r.steps, comebacks = comebacks, outAndBack = outAndBack }
end

M.routes = routes
if not rawget(_G, "EFFICIENCY_LIB") then
	local total, saved = 0, 0
	local rows = {}
	for _, r in ipairs(routes) do
		if (r.category or "Leveling") == "Leveling" then
			local f = M.route(r)
			total = total + f.walked
			local s = 0
			for _, c in ipairs(f.comebacks) do s = s + c.saved end
			saved = saved + s
			rows[#rows + 1] = { r = r, f = f, s = s }
		end
	end
	table.sort(rows, function(a, b) return a.s > b.s end)
	print(("%d leveling routes, %.0f yards walked in all; comeback stops could save %.0f yards"):format(#rows, total, saved))
	for _, row in ipairs(rows) do
		local f = row.f
		if #f.comebacks > 0 or #f.outAndBack > 0 then
			print(("\n%s (%d-%d): %d steps, %.0f yd walked"):format(row.r.id, row.r.levels[1], row.r.levels[2], f.steps, f.walked))
			for _, c in ipairs(f.comebacks) do
				local names = {}
				for _, g in ipairs(c.goals) do names[#names + 1] = g[1] .. " " .. g[2] .. " " .. (D.quests[g[2]] and D.quests[g[2]][1] or "?") end
				print(("  comeback: step %d (%s) could be done at step %d, saving %.0f yd: %s"):format(c.step, c.who, c.to, c.saved, table.concat(names, ", ")))
			end
			for _, o in ipairs(f.outAndBack) do
				print(("  out and back: step %d (%s), %.0f yd there and back%s"):format(o.step, row.r.steps[o.step].title or "?", o.yards, o.chain and " (a chain: needed)" or ""))
			end
		end
	end
end

return M
