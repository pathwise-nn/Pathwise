-- Writes Pathwise_Gear/Data/Gear.lua: what Best in Slot (Level) needs from
-- Pathwise's data (Pathwise/Data/Data.lua, built from QuestieDB's Forever
-- data), so it works for players who do not have Pathwise installed. Only
-- what it reads goes in, in the same layouts (by position) as Pathwise's:
--
--   gear      every entry, unchanged
--   quests    the reward quests: name [1], races [4], classes [5], map [6],
--             start npcs [7], start objects [8], exclusive to [15]
--   npcs      givers, drops, vendors and recipe sellers: name [1], side [4], spawns [5]
--   objects   quest start objects: name [1], spawns [2]
--   items     recipe items: name [1], first drop [2], first vendor [4]
--   dungeons  the instances gear drops in: name, levels, raid, entrances
--
--   lua5.1 tools/gear/data.lua            write it (npm run gear:data)
--   lua5.1 tools/gear/data.lua --check    exit 1 when it is out of date

local SRC, OUT = "Pathwise/Data/Data.lua", "Pathwise_Gear/Data/Gear.lua"

local ns = {}
assert(loadfile(SRC))("Pathwise", ns)
local D = ns.Data

local quests, npcs, objects, items, dungeons = {}, {}, {}, {}, {}

local function npc(id)
	local n = id and D.npcs[id]
	if n and not npcs[id] then npcs[id] = { n[1], nil, nil, n[4], n[5] } end
end

for _, g in pairs(D.gear) do
	for _, q in ipairs(g[5] or {}) do
		local d = D.quests[q]
		if d and not quests[q] then
			quests[q] = { d[1], nil, nil, d[4], d[5], d[6], d[7], d[8], nil, nil, nil, nil, nil, nil, d[15] }
			for _, n in ipairs(d[7] or {}) do npc(n) end
			for _, o in ipairs(d[8] or {}) do
				local ob = D.objects[o]
				if ob then objects[o] = { ob[1], ob[2] } end
			end
		end
	end
	for _, n in ipairs(g[6] or {}) do npc(n) end
	for _, n in ipairs(g[7] or {}) do npc(n) end
	local dg = g[9] and D.dungeons[g[9]]
	if dg then dungeons[g[9]] = { name = dg.name, levels = dg.levels, raid = dg.raid, entrances = dg.entrances } end
	local c = g[10]
	local it = c and c[4] and D.items[c[4]]
	if it then
		local drop, vendor = it[2] and it[2][1], it[4] and it[4][1]
		items[c[4]] = { it[1], drop and { drop } or nil, nil, vendor and { vendor } or nil }
		npc(drop)
		npc(vendor)
	end
end

---------------------------------------------------------------------------
-- Writing: plain Lua tables, keys sorted, so the file only changes with the data
---------------------------------------------------------------------------

local function key(k)
	if type(k) == "string" then return ("[%q]"):format(k) end
	return "[" .. tostring(k) .. "]"
end

local function value(v)
	local t = type(v)
	if t == "string" then return ("%q"):format(v) end
	if t == "number" then return (v == math.floor(v) and ("%d"):format(v)) or ("%.14g"):format(v) end
	if t == "boolean" then return tostring(v) end
	if t ~= "table" then return "nil" end
	local n = 0
	for i in pairs(v) do if type(i) == "number" and i > n and i == math.floor(i) then n = i end end
	local parts, seen = {}, {}
	-- The list part (holes as nil), then the rest by key.
	local count = 0
	for _ in pairs(v) do count = count + 1 end
	-- A list when its numbers are mostly 1..n; map IDs (1413, ...) are keys.
	local isList = n > 0 and n <= count * 2 + 16
	if isList then
		for i = 1, n do parts[#parts + 1] = value(v[i]) seen[i] = true end
	end
	local rest = {}
	for k in pairs(v) do if not seen[k] then rest[#rest + 1] = k end end
	table.sort(rest, function(a, b)
		if type(a) == type(b) then return a < b end
		return type(a) == "number"
	end)
	for _, k in ipairs(rest) do parts[#parts + 1] = key(k) .. "=" .. value(v[k]) end
	-- Trailing nils need not be written.
	while isList and parts[#parts] == "nil" do parts[#parts] = nil end
	return "{" .. table.concat(parts, ",") .. "}"
end

local function section(lines, name, t)
	local ids = {}
	for id in pairs(t) do ids[#ids + 1] = id end
	table.sort(ids)
	lines[#lines + 1] = ("G.%s = {"):format(name)
	for _, id in ipairs(ids) do lines[#lines + 1] = key(id) .. "=" .. value(t[id]) .. "," end
	lines[#lines + 1] = "}"
end

local function count(t) local n = 0 for _ in pairs(t) do n = n + 1 end return n end

local lines = {
	"-- GENERATED by tools/gear/data.lua from Pathwise/Data/Data.lua: do not edit.",
	"-- What Best in Slot (Level) needs, for players without Pathwise: run",
	"-- npm run gear:data after npm run data. The layouts are Pathwise's (by",
	"-- position); see tools/gear/data.lua.",
	("-- Source: %s. Data: the Questie team and contributors, used under GPL-3.0"):format(tostring(D.SOURCE)),
	"-- (THIRD_PARTY.md).",
	"",
	"local ADDON, ns = ...",
	"local G = {}",
	"ns.GearData = G",
	("G.SOURCE = %q"):format(tostring(D.SOURCE)),
}
section(lines, "gear", D.gear)
section(lines, "quests", quests)
section(lines, "npcs", npcs)
section(lines, "objects", objects)
section(lines, "items", items)
section(lines, "dungeons", dungeons)
local text = table.concat(lines, "\n") .. "\n"

local check = arg and arg[1] == "--check"
local f = io.open(OUT, "rb")
local have = f and f:read("*a")
if f then f:close() end
if check then
	if have ~= text then
		io.stderr:write(OUT .. " is out of date: run npm run gear:data\n")
		os.exit(1)
	end
	print(OUT .. " is up to date")
	return
end
local w = assert(io.open(OUT, "wb"))
w:write(text)
w:close()
print(("wrote %s: %d gear, %d quests, %d npcs, %d objects, %d items, %d dungeons"):format(OUT,
	count(D.gear), count(quests), count(npcs), count(objects), count(items), count(dungeons)))
