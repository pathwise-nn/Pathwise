-- Tests for Pathwise Loot: the generated data's shape, the catalog (bosses,
-- items, search, wishlist), the drops it learns in game (with secret values),
-- the browser, Pathwise Gear's upgrade marks, the tooltip line and the
-- minimap button.
local h = ...
local test, eq, ok = h.test, h.eq, h.ok

-- Forever's client APIs this addon calls, as a test wants them. Every test
-- sets them all, so none leaks from one test into the next.
local function client(o)
	o = o or {}
	return function(s)
		_G.Pathwise = o.pathwise
		Enum = Enum or {}
		Enum.LootSlotType = { None = 0, Item = 1, Money = 2, Currency = 3 }
		s.loot = o.loot or {} -- loot window slots: { link, source GUID }
		s.drops = o.drops or {} -- C_LootHistory: [encounterID .. ":" .. key] = info
		s.bossGUID = o.bossGUID or {}
		s.instanceInfo = o.instanceInfo
		C_LootHistory = { GetSortedInfoForDrop = function(eid, key) return s.drops[eid .. ":" .. key] end }
		function GetNumLootItems() return #s.loot end
		function GetLootSlotType(i) return s.loot[i] and (s.loot[i].kind or 1) or 0 end
		function GetLootSlotLink(i) return s.loot[i] and s.loot[i][1] end
		GetLootSourceInfo = (not o.noSourceInfo) and function(i) return s.loot[i] and s.loot[i][2] end or nil
		function GetInstanceInfo()
			local i = s.instanceInfo
			if not i then return nil end
			return i.name, i.kind, 0, "", 40, 0, false, i.map
		end
		function UnitGUID(u) return s.bossGUID[u] end
		local exists = UnitExists
		function UnitExists(u) if s.bossGUID[u] then return true end return exists(u) end
		function IsModifiedClick() return o.modified or false end
		s.modifiedClicks = {}
		function HandleModifiedItemClick(link) s.modifiedClicks[#s.modifiedClicks + 1] = link return true end
		if o.setup then o.setup(s) end
	end
end

local function fresh(o) return h.fresh(client(o)) end

-- An encounter fought and won (the client's events, in order).
local function kill(stub, id, name)
	stub.fire("ENCOUNTER_START", id, name, 0, 40)
	stub.fire("ENCOUNTER_END", id, name, 0, 40, 1)
end

-- An encounter whose data has both a monster and drops.
local function bossWithLoot(ns)
	local D = ns.LootData
	for _, inst in ipairs(D.INSTANCES) do
		for _, eid in ipairs(inst[6]) do
			local e = D.ENCOUNTERS[eid]
			if #e[4] > 0 and #e[5] > 0 then return eid, e, inst end
		end
	end
end

local function itemNotDropped(ns)
	local id = 900000
	while ns.LootData.ITEMS[id] do id = id + 1 end
	return id
end

