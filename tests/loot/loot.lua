test("learn: a kill and the group's loot roll add the drop to that boss, once", function()
	local stub, ns = fresh()
	local L = ns.Loot
	local unknown = itemNotDropped(ns)
	kill(stub, 672, "Ragnaros")
	eq(L.Encounter(672).kills, 1, "a kill counted")
	stub.drops["672:1"] = { itemHyperlink = "|cffa335ee|Hitem:17076::::::::60:::::|h[Bonereaver's Edge]|h|r" }
	stub.drops["672:2"] = { itemHyperlink = "item:" .. unknown }
	stub.fire("LOOT_HISTORY_UPDATE_DROP", 672, 1)
	stub.fire("LOOT_HISTORY_UPDATE_DROP", 672, 1)
	stub.fire("LOOT_HISTORY_UPDATE_DROP", 672, 2)
	local e = L.Encounter(672)
	local byId = {}
	for _, entry in ipairs(e.loot) do byId[entry.id] = entry end
	eq(byId[17076].seen, 1, "seen once, though the history updated twice")
	ok(byId[17076].data, "and still the data's")
	ok(byId[unknown] and byId[unknown].seen == 1 and not byId[unknown].data, "a drop the data lacks is added")
	ok(PathwiseLootSettings.data.seen[672], "kept for every character")
	-- The next kill counts again.
	kill(stub, 672, "Ragnaros")
	stub.fire("LOOT_HISTORY_UPDATE_DROP", 672, 1)
	local function seenNow()
		for _, entry in ipairs(L.Encounter(672).loot) do if entry.id == 17076 then return entry.seen end end
	end
	eq(L.Encounter(672).kills, 2)
	eq(seenNow(), 2, "the next kill's roll counts, though its key is the same")
	stub.fire("ENCOUNTER_LOOT_RECEIVED", 672, 17076, "item:17076", 1, "Someone", "WARRIOR")
	eq(seenNow(), 2, "once per kill: the roll and the loot received are one drop")
end)

