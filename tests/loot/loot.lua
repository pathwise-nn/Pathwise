test("learn: a boss's corpse and a chest opened just after the kill", function()
	local stub, ns = fresh()
	local L = ns.Loot
	local eid, e = bossWithLoot(ns)
	local npc = e[4][1]
	local extra = itemNotDropped(ns)
	stub.loot = { { "item:" .. extra, ("Creature-0-1465-0-2105-%d-000043F59F"):format(npc) } }
	stub.fire("LOOT_OPENED")
	local function seen(id, item)
		for _, entry in ipairs(L.Encounter(id).loot) do if entry.id == item then return entry.seen end end
	end
	eq(seen(eid, extra), 1, "the corpse names its boss")
	stub.fire("LOOT_OPENED")
	eq(seen(eid, extra), 1, "the same corpse twice is one drop")
	-- A chest with no kill before it: nobody's.
	stub.loot = { { "item:" .. (extra + 1), "GameObject-0-1465-0-2105-179703-000043F59F" } }
	stub.fire("LOOT_OPENED")
	eq(seen(eid, extra + 1), nil, "a chest with no kill before it is no boss's")
	-- Just after a kill, the chest is that boss's.
	kill(stub, 671, "Majordomo Executus")
	stub.fire("LOOT_OPENED")
	eq(seen(671, extra + 1), 1, "the chest after Majordomo")
	-- A while later it is not.
	stub.now = stub.now + 600
	stub.loot = { { "item:" .. (extra + 2), "GameObject-0-1465-0-2105-179703-000043F5A0" } }
	stub.fire("LOOT_OPENED")
	eq(seen(671, extra + 2), nil, "too long after the kill")
	-- Money and a secret source are skipped.
	stub.loot = { { "item:" .. (extra + 3), stub.Secret("Creature-0-1-0-1-" .. npc .. "-1") }, { nil, nil, kind = 2 } }
	stub.fire("LOOT_OPENED")
	eq(seen(eid, extra + 3), nil, "a secret source is no source")
end)

