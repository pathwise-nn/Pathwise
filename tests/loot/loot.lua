test("data: every boss and item it lists exists, with the right shape", function()
	local _, ns = fresh()
	local D = ns.LootData
	ok(#D.INSTANCES >= 30, "Forever's dungeons and raids")
	local raids, inRaid = 0, false
	local listed = {}
	for i, inst in ipairs(D.INSTANCES) do
		ok(type(inst[1]) == "number" and type(inst[2]) == "string" and inst[2] ~= "", "instance " .. i .. " has a map and a name")
		ok(type(inst[3]) == "boolean", inst[2] .. ": raid or not")
		if inst[3] then raids = raids + 1 inRaid = true else ok(not inRaid, inst[2] .. ": dungeons come before raids") end
		ok(#inst[6] > 0, inst[2] .. " has bosses")
		for _, eid in ipairs(inst[6]) do
			ok(D.ENCOUNTERS[eid], inst[2] .. ": boss " .. eid .. " is in ENCOUNTERS")
			eq(D.ENCOUNTERS[eid][2], inst[1], "boss " .. eid .. "'s map")
			ok(not listed[eid], "boss " .. eid .. " listed once")
			listed[eid] = true
		end
	end
	ok(raids >= 6, "the raids")
	local withLoot = 0
	for eid, e in pairs(D.ENCOUNTERS) do
		ok(listed[eid], "boss " .. eid .. " is under an instance")
		ok(type(e[1]) == "string" and e[1] ~= "", "boss " .. eid .. " has a name")
		ok(type(e[4]) == "table" and type(e[5]) == "table", "boss " .. eid .. " has npc and item lists")
		if #e[5] > 0 then withLoot = withLoot + 1 ok(#e[4] > 0, "boss " .. eid .. ": drops come from a monster") end
		for _, item in ipairs(e[5]) do ok(D.ITEMS[item], "boss " .. eid .. ": item " .. item .. " is in ITEMS") end
	end
	ok(withLoot >= 150, "most bosses have drops in the data")
	for id, it in pairs(D.ITEMS) do
		ok(type(it[1]) == "string" and it[1] ~= "", "item " .. id .. " has a name")
		for k = 2, 7 do ok(type(it[k]) == "number", "item " .. id .. " field " .. k) end
	end
	ok(D.BUILD:match("^1%.60%.") and D.QUESTIEDB ~= "", "names its sources")
end)

